class ScoringService:

    def __init__(self, db: Client) -> None:
        self._db = db

    def score_company(self, company_id: str, icp_id: str) -> LeadScore:
        company = self._load_company(company_id)
        icp = self._load_icp(icp_id)
        evidence = self._load_evidence(company_id)
        score = self._compute_score(company, icp, evidence)
        self._persist_score(score)
        logger.info("company_scored", domain=company.get("domain"),
                    total=score.total_score, category=score.score_category)
        return score

    def score_batch(self, search_id: str, icp_id: str,
                    min_research_confidence: float = 0.0) -> ScoreBatchResponse:
        companies = self._load_complete_companies(search_id)
        icp = self._load_icp(icp_id)
        scores: list[LeadScore] = []
        skipped = 0

        for company in companies:
            company_id = company["id"]
            if self._already_scored(company_id):
                skipped += 1
                continue
            # ScoreBatchRequest.min_research_confidence (schemas/score.py) is
            # documented as "skip companies whose data_confidence is below
            # this threshold" with default 0.0 — i.e. the caller's value is
            # the actual threshold, not a floor that gets raised. Silently
            # enforcing max(_MIN_CONFIDENCE_TO_SCORE, min_research_confidence)
            # here meant a caller explicitly passing 0.0 to see everything
            # still had companies in the 0.0-0.10 confidence range silently
            # skipped, contradicting the documented contract.
            if company.get("data_confidence", 0.0) < min_research_confidence:
                skipped += 1
                continue
            try:
                evidence = self._load_evidence(company_id)
                score = self._compute_score(company, icp, evidence)
                self._persist_score(score)
                scores.append(score)
                logger.info("batch_scored", domain=company.get("domain"), total=score.total_score)
            except Exception as exc:
                logger.warning("batch_score_failed", company_id=company_id, error=str(exc))
                skipped += 1

        return ScoreBatchResponse(
            scored=len(scores), skipped=skipped, total=len(companies),
            scores=sorted(scores, key=lambda s: s.total_score, reverse=True),
        )

    def _compute_score(self, company: dict, icp: dict,
                        evidence: list[dict]) -> LeadScore:
        # Defensive normalization: `.get(field, default)` only applies the
        # default when the key is *missing*, not when the stored value is
        # explicitly None/null. If any of these ever get persisted as null
        # (e.g. an older row, a partial upsert), every downstream dimension
        # method below does `company.get("services", []) + [...]` or
        # `for t in company.get("technologies", [])` — either of which
        # raises on None and would silently drop that company out of
        # scoring/batch's results (caught by its blanket try/except and
        # counted as "skipped" with no visible error). Normalizing once
        # here means every dimension method can keep assuming a real
        # list/string without each needing its own guard.
        company = dict(company)
        for list_field in ("services", "technologies", "job_titles_found"):
            company[list_field] = company.get(list_field) or []
        for str_field in ("industry", "location", "employee_range", "discovery_snippet"):
            company[str_field] = company.get(str_field) or ""

        ev_by_field: dict[str, list[dict]] = {}
        for ev in evidence:
            ev_by_field.setdefault(ev["field_name"], []).append(ev)

        icp_dim    = self._score_icp_match(company, icp, ev_by_field)
        ind_dim    = self._score_industry_fit(company, icp, ev_by_field)
        size_dim   = self._score_company_size(company, icp, ev_by_field)
        growth_dim = self._score_growth_signals(company, icp, ev_by_field)
        hiring_dim = self._score_hiring_signals(company, ev_by_field)
        auto_dim   = self._score_automation_opportunity(company, icp, ev_by_field)
        disq_dim   = self._compute_disqualifier_penalty(company, icp, ev_by_field)

        raw = (icp_dim.score + ind_dim.score + size_dim.score +
               growth_dim.score + hiring_dim.score + auto_dim.score)
        total = max(0, min(100, raw + disq_dim.score))

        return LeadScore(
            company_id=company["id"],
            icp_match=icp_dim, industry_fit=ind_dim, company_size=size_dim,
            growth_signals=growth_dim, hiring_signals=hiring_dim,
            automation_opportunity=auto_dim, disqualifiers=disq_dim,
            total_score=total, score_category=categorize_score(total),
            scored_at=datetime.now(timezone.utc),
        )

    def _score_icp_match(self, company, icp, ev_by_field) -> ScoreDimension:
        MAX = 15  # reduced from 25 — see schemas/score.py module docstring:
                  # this dimension requires a company's own copy to echo
                  # free-form ICP sentences, a bar real sites rarely clear
        score = 0
        ev_ids: list[str] = []
        reasons: list[str] = []

        company_text = " ".join(
            company.get("services", []) +
            [company.get("industry", ""), company.get("discovery_snippet", "") or ""]
        ).lower()

        # signal_overlap_hits (significant-token overlap), not keyword_overlap
        # (whole-sentence substring): ICP pain_points/positive_signals are
        # free-form Groq-generated sentences that essentially never appear
        # verbatim in extracted evidence — see utils/text.signal_overlap_hits
        # for the full rationale (same class of bug already fixed for
        # disqualifiers).
        pain_hits = signal_overlap_hits(company_text, icp.get("pain_points", []))
        pain_score = min(6, len(pain_hits) * 2)
        score += pain_score
        if pain_hits:
            reasons.append(f"matches {len(pain_hits)} pain point(s): {', '.join(pain_hits[:2])}")
            ev_ids += [e["id"] for e in ev_by_field.get("service", [])[:3]]

        # positive_signals frequently describe hiring/job-posting evidence
        # ("job posting for machine learning or AI engineer") — include
        # job_titles_found so an actual matching job title can be detected,
        # not just service/industry copy. discovery_snippet is the original
        # search-result text and can carry signal (e.g. a page literally
        # titled "AI and Machine Learning careers") that P1-crawled pages
        # didn't happen to restate.
        pos_corpus = " ".join(
            company.get("services", []) +
            company.get("technologies", []) +
            company.get("job_titles_found", []) +
            [company.get("industry", ""), company.get("discovery_snippet", "") or ""]
        ).lower()
        pos_hits = signal_overlap_hits(pos_corpus, icp.get("positive_signals", []))
        pos_score = min(6, len(pos_hits) * 2)
        score += pos_score
        if pos_hits:
            reasons.append(f"matches {len(pos_hits)} positive signal(s)")
            ev_ids += [e["id"] for e in ev_by_field.get("technology", [])[:2]]
            ev_ids += [e["id"] for e in ev_by_field.get("job_title", [])[:2]]

        target_locs = [l.lower() for l in icp.get("target_locations", [])]
        loc = company.get("location", "").lower()
        location_matched = bool(loc) and any(tl in loc for tl in target_locs)

        # Whole-phrase substring matching misses the extremely common case
        # of a US city/state address ("Atlanta, GA") when the ICP target
        # is the country name ("United States") — neither string contains
        # the other verbatim. Matched against the real list of US state/
        # territory abbreviations (not just "any 2-letter code after a
        # comma" — that loose version incorrectly matched "London, UK",
        # since UK is also 2 letters). This does not attempt to generalize
        # to every country's local address formats, only the one gap
        # directly evidenced in review.
        if not location_matched and "united states" in target_locs:
            match = re.search(r",\s*([a-z]{2})\b", loc)
            if match and match.group(1).upper() in _US_STATE_CODES:
                location_matched = True

        if location_matched:
            score += 3
            reasons.append("location matches ICP target region")
            ev_ids += [e["id"] for e in ev_by_field.get("location", [])[:1]]

        return ScoreDimension(
            score=min(MAX, score), max_score=MAX,
            reason="; ".join(reasons) or "No significant ICP signal overlap",
            evidence_ids=list(set(ev_ids)),
        )

    @staticmethod
    def _expanded_target_tokens(target: str) -> set[str]:
        """Expanded (synonym-bridged) token set for one ICP target_industries
        phrase — used only to compute overlap *coverage* in
        _score_industry_fit, not to find the match itself (that's still
        industry_token_overlap's job)."""
        return _expand_industry_synonyms(significant_tokens(target))

    def _score_industry_fit(self, company, icp, ev_by_field) -> ScoreDimension:
        MAX = 25  # increased from 20 — deterministic, reliable signal
        ci = (company.get("industry") or "").lower()
        targets = [i.lower() for i in icp.get("target_industries", [])]
        ev_ids = [e["id"] for e in ev_by_field.get("industry", [])[:1]]

        if not ci:
            return ScoreDimension(score=0, max_score=MAX,
                                   reason="Industry not detected", evidence_ids=[])
        if ci in targets:
            return ScoreDimension(score=MAX, max_score=MAX,
                                   reason=f"Industry '{company.get('industry')}' directly matches ICP",
                                   evidence_ids=ev_ids)

        # Whole-phrase substring matching misses cases where two labels
        # describe the same real-world category with different wording —
        # e.g. ICP target "logistics companies" vs extracted industry
        # "Logistics & Supply Chain": neither string contains the other
        # verbatim, so `t in ci or ci in t` was always False here even
        # though both obviously mean the same industry. Token-overlap
        # comparison strips generic words ("companies", "&") and compares
        # the remaining significant words instead.
        best_shared: set[str] = set()
        for t in targets:
            shared = industry_token_overlap(ci, t)
            if len(shared) > len(best_shared):
                best_shared = shared
        # Previously a flat 15/25 for ANY non-empty overlap — that gave a
        # company sharing 11 of 17 expanded target tokens (e.g. Automotive
        # vs "auto repair shops") the exact same score as one sharing just
        # 1 incidental token, and permanently capped every non-literal
        # match at 60% even when the synonym bridge is a confirmed,
        # human-curated same-category signal (see _INDUSTRY_SYNONYMS).
        # Scaled by overlap coverage instead: coverage = shared tokens /
        # matched target's own expanded token count. Floor of 14 (still
        # clearly above a 0/no-match) for any real overlap, ceiling of 24
        # (one point short of an exact-string match, which stays the only
        # way to hit the true max) for near-total coverage.
        if best_shared:
            best_target_tokens = max(
                (self._expanded_target_tokens(t) for t in targets),
                key=lambda toks: len(best_shared & toks),
                default=best_shared,
            )
            coverage = len(best_shared) / max(1, len(best_target_tokens))
            partial_score = round(14 + 10 * min(1.0, coverage))
            return ScoreDimension(
                score=partial_score, max_score=MAX,
                reason=f"Industry '{company.get('industry')}' partially matches ICP "
                       f"(shared terms: {', '.join(sorted(best_shared))})",
                evidence_ids=ev_ids,
            )
        return ScoreDimension(score=0, max_score=MAX,
                               reason=f"Industry '{company.get('industry')}' does not match ICP",
                               evidence_ids=ev_ids)

    def _score_company_size(self, company, icp, ev_by_field) -> ScoreDimension:
        MAX = 20  # increased from 15 — deterministic, reliable signal
        cr = company.get("employee_range", "")
        targets = icp.get("target_company_sizes", [])
        ev_ids = [e["id"] for e in ev_by_field.get("employee_range", [])[:1]]

        if not cr or not targets:
            # RECALIBRATED (was 7/20): this project's own notes flagged
            # recalibrating this kind of default as premature without real
            # usage data — that data now exists. Across four different live
            # ICP tests (auto repair shops, small law firms, manufacturing/
            # warehouse employers, independent hotels), the single most
            # common reason a genuinely good-fit small business landed
            # below the qualification threshold was a correct industry
            # match dragged down by "size unknown" scoring at only 35%
            # credit — not because the company was actually a bad fit, but
            # because small independent businesses (exactly this
            # platform's target population) very rarely state headcount on
            # their own marketing site. Confirmed case: Archer Hotel, a
            # real small boutique hotel correctly tagged Hospitality,
            # scored 39/100 overall and missed qualification by 1 point.
            # Meanwhile companies whose size IS large are usually
            # extractable or otherwise flagged (e.g. "1000+", or simply
            # excluded by industry/location mismatch) — so raising this
            # default mainly helps the population it should help, without
            # meaningfully opening the door for large companies to sneak
            # through on this dimension alone.
            return ScoreDimension(score=12, max_score=MAX,
                                   reason="Company size unknown — partial credit", evidence_ids=[])
        if cr in targets:
            return ScoreDimension(score=MAX, max_score=MAX,
                                   reason=f"Size '{cr}' matches ICP target", evidence_ids=ev_ids)
        try:
            ci = _SIZE_TIERS.index(cr)
            tis = [_SIZE_TIERS.index(s) for s in targets if s in _SIZE_TIERS]
            if tis:
                dist = min(abs(ci - ti) for ti in tis)
                if dist == 1:
                    return ScoreDimension(score=11, max_score=MAX,
                                           reason=f"Size '{cr}' adjacent to ICP target",
                                           evidence_ids=ev_ids)
                if dist == 2:
                    return ScoreDimension(score=4, max_score=MAX,
                                           reason=f"Size '{cr}' somewhat outside ICP target",
                                           evidence_ids=ev_ids)
        except ValueError:
            pass
        return ScoreDimension(score=0, max_score=MAX,
                               reason=f"Size '{cr}' outside ICP target range",
                               evidence_ids=ev_ids)

    def _score_growth_signals(self, company, icp, ev_by_field) -> ScoreDimension:
        MAX = 20
        score = 0
        ev_ids: list[str] = []
        reasons: list[str] = []

        if company.get("booking_detected"):
            score += 5
            reasons.append("online booking widget detected")
            ev_ids += [e["id"] for e in ev_by_field.get("booking_widget", [])[:1]]

        tech_hits = [t for t in company.get("technologies", []) if t in _GROWTH_TECH_SIGNALS]
        tech_score = min(5, len(tech_hits) * 2)
        score += tech_score
        if tech_hits:
            reasons.append(f"growth tech: {', '.join(tech_hits[:2])}")
            ev_ids += [e["id"] for e in ev_by_field.get("technology", [])[:2]]

        company_text = " ".join(
            company.get("services", []) +
            [company.get("location", ""), company.get("industry", "")]
        ).lower()
        trigger_hits = keyword_overlap(company_text, icp.get("buying_triggers", []))
        score += min(5, len(trigger_hits) * 2)
        if trigger_hits:
            reasons.append(f"matches {len(trigger_hits)} buying trigger(s)")

        if company.get("hiring_signals"):
            score += 5
            reasons.append("active hiring indicates growth")
            ev_ids += [e["id"] for e in ev_by_field.get("hiring_signal", [])[:1]]

        return ScoreDimension(
            score=min(MAX, score), max_score=MAX,
            reason="; ".join(reasons) or "No significant growth signals",
            evidence_ids=list(set(ev_ids)),
        )

    def _score_hiring_signals(self, company, ev_by_field) -> ScoreDimension:
        MAX = 15  # increased from 10 — deterministic, reliable signal
        ev_ids = [e["id"] for e in ev_by_field.get("hiring_signal", [])[:1]]
        if not company.get("hiring_signals"):
            return ScoreDimension(score=0, max_score=MAX,
                                   reason="No active hiring signals found", evidence_ids=[])
        titles = company.get("job_titles_found", [])
        if titles:
            preview = ", ".join(titles[:3]) + ("..." if len(titles) > 3 else "")
            return ScoreDimension(score=MAX, max_score=MAX,
                                   reason=f"Actively hiring: {preview}", evidence_ids=ev_ids)
        return ScoreDimension(score=9, max_score=MAX,
                               reason="Hiring language detected, no specific roles identified",
                               evidence_ids=ev_ids)

    def _score_automation_opportunity(self, company, icp, ev_by_field) -> ScoreDimension:
        MAX = 5  # reduced from 10 — weak, low-information signal in practice
        score = 0
        reasons: list[str] = []

        text = " ".join(company.get("services", []) +
                        [company.get("industry", "")]).lower()
        manual_hits = keyword_overlap(text, _AUTOMATION_KEYWORDS)
        manual_score = min(3, len(manual_hits))
        score += manual_score
        if manual_hits:
            reasons.append(f"manual process signals: {', '.join(manual_hits[:2])}")

        service_industries = {"dental", "healthcare", "legal", "accounting",
                               "consulting", "fitness", "beauty", "medical"}
        if any(kw in text for kw in service_industries) and not company.get("booking_detected"):
            score += 1
            reasons.append("service business without online booking")

        if not company.get("technologies"):
            score += 1
            reasons.append("no technology signals detected")

        return ScoreDimension(
            score=min(MAX, score), max_score=MAX,
            reason="; ".join(reasons) or "No clear operational signals detected",
            evidence_ids=[],
        )

    def _compute_disqualifier_penalty(self, company, icp, ev_by_field) -> ScoreDimension:
        """
        Deduct points for ICP disqualifying_signals matched in the company's
        own evidence. Returns a ScoreDimension (not a bare int) so the
        deduction is exposed in the API response with its own reason text
        and — where the hit came from a specific evidence field — the
        evidence_ids that drove it, exactly like every other dimension.
        max_score is 0 since this dimension only ever deducts.
        """
        disqualifiers = icp.get("disqualifying_signals", [])
        if not disqualifiers:
            return ScoreDimension(score=0, max_score=0,
                                   reason="No disqualifying signals defined in ICP",
                                   evidence_ids=[])

        text = " ".join(company.get("services", []) +
                        company.get("technologies", []) +
                        [company.get("industry", "")]).lower()

        # Literal check (unchanged): still useful for short, keyword-like
        # disqualifying signals that genuinely can appear verbatim.
        literal_hits = keyword_overlap(text, disqualifiers)
        penalty = min(15, len(literal_hits) * 5)
        reasons: list[str] = list(literal_hits)

        # Vendor/agency category detection — see _VENDOR_AGENCY_PHRASES for
        # rationale. Only runs when the ICP itself is asking to disqualify
        # this category (checked via _VENDOR_DISQUALIFIER_TRIGGERS), and
        # only fires with enough distinct evidence to avoid false-positives
        # on genuine buyers that happen to mention "consulting" once.
        if self._icp_disqualifies_vendors(disqualifiers):
            service_texts = [s.lower() for s in company.get("services", [])]
            vendor_hits = sorted({
                phrase for phrase in _VENDOR_AGENCY_PHRASES
                if phrase in text or any(phrase in s for s in service_texts)
            })
            industry_name = company.get("industry") or ""
            # crawlers/extractors/industry.py's dedicated "AI/Software
            # Development Agency" classification already requires a
            # decisive, unambiguous phrase match to be assigned at all, so
            # it's trusted on its own. "Technology"/"Consulting" are much
            # broader labels that legitimate buyers get too, so those still
            # require at least one service-level phrase hit alongside them.
            is_agency_industry = industry_name == "AI/Software Development Agency"
            industry_suggests_vendor = industry_name in {"Technology", "Consulting"}
            if is_agency_industry or (vendor_hits and (len(vendor_hits) >= 2 or industry_suggests_vendor)):
                penalty += 40  # strong, near-disqualifying penalty — this is
                               # a clear match to a hard disqualifying category,
                               # not a soft/partial signal like the ones above.
                matched = vendor_hits[:3] or [industry_name]
                reasons.append(
                    "company appears to sell AI/software development "
                    f"services itself (matched: {', '.join(matched)})"
                )

        if not reasons:
            return ScoreDimension(score=0, max_score=0,
                                   reason="No disqualifying signals detected",
                                   evidence_ids=[])

        penalty = min(60, penalty)
        ev_ids = (
            [e["id"] for e in ev_by_field.get("industry", [])[:1]] +
            [e["id"] for e in ev_by_field.get("service", [])[:1]] +
            [e["id"] for e in ev_by_field.get("technology", [])[:1]]
        )
        return ScoreDimension(
            score=-penalty, max_score=0,
            reason=f"Disqualifying signal(s) detected: {', '.join(reasons)}",
            evidence_ids=ev_ids,
        )

    @staticmethod
    def _icp_disqualifies_vendors(disqualifiers: list[str]) -> bool:
        """Whether any ICP disqualifying_signal describes the 'sells AI/
        software development services' category (see _VENDOR_DISQUALIFIER_TRIGGERS)."""
        for d in disqualifiers:
            if significant_tokens(d) & _VENDOR_DISQUALIFIER_TRIGGERS:
                return True
        return False

    def _persist_score(self, score: LeadScore) -> None:
        breakdown = {
            dim: {
                "score": getattr(score, dim).score,
                "max_score": getattr(score, dim).max_score,
                "reason": getattr(score, dim).reason,
                "evidence_ids": getattr(score, dim).evidence_ids,
            }
            for dim in ["icp_match", "industry_fit", "company_size",
                        "growth_signals", "hiring_signals", "automation_opportunity",
                        "disqualifiers"]
        }
        all_ev_ids = list(set(
            score.icp_match.evidence_ids + score.industry_fit.evidence_ids +
            score.company_size.evidence_ids + score.growth_signals.evidence_ids +
            score.hiring_signals.evidence_ids + score.automation_opportunity.evidence_ids +
            score.disqualifiers.evidence_ids
        ))
        try:
            self._db.table("lead_scores").upsert({
                "id": str(uuid.uuid4()),
                "company_id": score.company_id,
                "icp_match": score.icp_match.score,
                "industry_fit": score.industry_fit.score,
                "company_size": score.company_size.score,
                "growth_signals": score.growth_signals.score,
                "hiring_signals": score.hiring_signals.score,
                "automation_opportunity": score.automation_opportunity.score,
                "total_score": score.total_score,
                "score_category": score.score_category,
                "score_breakdown": breakdown,
                "evidence_used": all_ev_ids,
                "scored_at": score.scored_at.isoformat(),
            }, on_conflict="company_id").execute()
        except Exception as exc:
            logger.error("persist_score_failed", company_id=score.company_id, error=str(exc))
            raise

    def _load_company(self, company_id: str) -> dict:
        result = self._db.table("companies").select("*").eq("id", company_id).single().execute()
        if not result.data:
            raise ValueError(f"Company {company_id} not found")
        return result.data

    def _load_icp(self, icp_id: str) -> dict:
        result = (
            self._db.table("icps")
            .select("target_industries, target_company_sizes, target_locations, "
                    "pain_points, buying_triggers, positive_signals, disqualifying_signals")
            .eq("id", icp_id).single().execute()
        )
        if not result.data:
            raise ValueError(f"ICP {icp_id} not found")
        return result.data

    def _load_evidence(self, company_id: str) -> list[dict]:
        result = (
            self._db.table("evidence")
            .select("id, field_name, value, confidence, trust_level, source_url")
            .eq("company_id", company_id).lte("trust_level", 2).execute()
        )
        return result.data or []

    def _load_complete_companies(self, search_id: str) -> list[dict]:
        result = (
            self._db.table("companies")
            .select("id, domain, industry, employee_range, services, technologies, "
                    "hiring_signals, job_titles_found, location, booking_detected, "
                    "discovery_snippet, data_confidence, research_status")
            .eq("search_id", search_id).eq("research_status", "complete").execute()
        )
        return result.data or []

    def _already_scored(self, company_id: str) -> bool:
        try:
            result = (self._db.table("lead_scores").select("id")
                      .eq("company_id", company_id).limit(1).execute())
            return bool(result.data)
        except Exception:
            return False