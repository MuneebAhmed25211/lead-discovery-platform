"""
schemas/qualification.py
────────────────────────
Schemas for Groq-powered qualification and outreach generation.

Qualification (Groq call #2):
  Input:  structured P1 facts + lead score
  Output: why_qualified, pain_points, suggested_services,
          outreach_angle, buying_triggers

Outreach (Groq call #3):
  Input:  company facts + qualification output
  Output: 4 message variants (LinkedIn, cold email, audit opener, follow-up)
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import StrEnum
from uuid import UUID

from pydantic import Field

from schemas.common import AppBaseModel, UUIDModel


# ── Qualification ─────────────────────────────────────────────────────────────

class QualificationStatus(StrEnum):
    """How strongly this company matches the ICP, per Groq's evidence-grounded analysis."""
    QUALIFIED = "qualified"
    PARTIALLY_QUALIFIED = "partially_qualified"
    NOT_QUALIFIED = "not_qualified"


class Qualification(AppBaseModel):
    """
    Groq-generated qualification analysis.

    All fields must be grounded in P1 evidence — the prompt enforces this.
    No hallucinated claims about the company are allowed.

    Field mapping to the Phase 5 spec's suggested output names (kept as
    why_qualified/suggested_services/outreach_angle rather than renamed to
    fit_summary/recommended_service/likely_buying_reason because these
    field names are the existing `qualifications` table's actual columns
    — see supabase/migrations/001_initial_schema.sql — and Phase 5 must
    not change existing database schema):
      qualification_status  → new field, see QualificationStatus
      fit_summary            → why_qualified
      primary_pain_points    → pain_points
      recommended_service    → suggested_services
      likely_buying_reason   → outreach_angle
      confidence             → new field
      reasoning               → why_qualified + evidence_summary together
    """

    company_id: str

    # How strongly this company matches the ICP
    qualification_status: QualificationStatus = Field(
        ...,
        description="Overall fit verdict: qualified, partially_qualified, or not_qualified.",
    )

    # Model's self-assessed confidence in this qualification, grounded in
    # how much/how strong the underlying evidence is — not a vibe score.
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Groq's confidence in this qualification, 0.0–1.0.",
    )

    # Why this company qualifies
    why_qualified: str = Field(
        ...,
        description="2–4 sentences citing specific evidence from the company's own website.",
    )

    # Specific operational pain points identified
    pain_points: list[str] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="Concrete pain points this company likely has based on P1 evidence.",
    )

    # What services to pitch
    suggested_services: list[str] = Field(
        ...,
        min_length=1,
        max_length=3,
        description="Specific services from the user's offering that address these pain points.",
    )

    # How to angle the outreach
    outreach_angle: str = Field(
        ...,
        description="Single sentence describing the most compelling outreach angle.",
    )

    # What events to watch for
    buying_triggers: list[str] = Field(
        default_factory=list,
        description="Signs this company might be ready to buy (hiring, expansion, etc.)",
    )

    # Evidence transparency
    evidence_summary: str = Field(
        default="",
        description="Which P1 pages were used to generate this qualification.",
    )

    groq_model: str = ""
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# ── Outreach ──────────────────────────────────────────────────────────────────

class OutreachVariant(AppBaseModel):
    """A single outreach message variant."""

    type: str     # "linkedin" | "cold_email" | "audit_opener" | "followup"
    subject: str = ""   # email subject line (only for cold_email)
    body: str


class Outreach(AppBaseModel):
    """
    4 outreach message variants generated by Groq.

    Requirements:
    - Personalized: references specific things from the company's site
    - Human-sounding: no AI buzzwords, no generic openers
    - Specific: names a real pain point or observation
    - Grounded: doesn't claim things we don't have evidence for
    """

    company_id: str
    linkedin_message: OutreachVariant
    cold_email: OutreachVariant
    audit_opener: OutreachVariant
    followup_message: OutreachVariant

    groq_model: str = ""
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @property
    def all_variants(self) -> list[OutreachVariant]:
        return [
            self.linkedin_message,
            self.cold_email,
            self.audit_opener,
            self.followup_message,
        ]


