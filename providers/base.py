"""
providers/base.py
──────────────────
Abstract base class for search providers.

Every concrete provider (Serper, Tavily) implements this contract.
The router (providers/router.py) depends only on this interface, never
on a concrete provider class — this is what makes the fallback chain
provider-agnostic and means adding or removing a provider never touches
router logic, only configuration.

Design constraints enforced by this contract:
  - search() is always async (both providers are called via httpx.AsyncClient)
  - search() NEVER raises for "no results" — empty list is a valid, successful
    outcome. It DOES raise for actual failures (timeout, auth error, 5xx) —
    the router is responsible for catching those and falling back.
  - Every provider declares its own `name` for logging/persistence.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

from schemas.discovery import SearchResult


class SearchProviderError(Exception):
    """
    Raised by a provider's search() method when the call itself failed —
    timeout, non-2xx response, malformed response body, or auth failure.

    This is distinct from a successful call returning zero results, which
    is NOT an error and must return an empty list instead of raising.
    """

    def __init__(self, provider: str, message: str) -> None:
        self.provider = provider
        self.message = message
        super().__init__(f"[{provider}] {message}")


class SearchProvider(ABC):
    """Abstract contract every search provider must implement."""

